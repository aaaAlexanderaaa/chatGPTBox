/* eslint-env node */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import prettier from 'prettier'

const sourceDirectory = fileURLToPath(new URL('./drafts/', import.meta.url))
const directory = fileURLToPath(new URL('../docs/drafts/', import.meta.url))
const read = (name) => fs.readFileSync(path.join(sourceDirectory, name), 'utf8').trim()
const chatgptFiles = {
  list: 'action-1-list-conversations.js',
  get: 'action-2-open-checked-conversation.js',
  send: 'action-3-send-waiting-reply.js',
  photos: 'action-4-attach-photos.js',
  project: 'action-5-select-project.js',
}

function chatgptAdapter(operation) {
  let source = read('chatgpt/' + chatgptFiles[operation] + '.txt')
  source = source.replace(/\/\* global [^\n]*?\*\/\n?/g, '')
  for (const [name, text] of [
    ['CONTROL DOCUMENT', read('control-document.shared.txt')],
    ['PHOTO HELPERS', read('photo-operation.shared.txt')],
  ])
    source = source.replace(
      new RegExp('// BEGIN ' + name + '[\\s\\S]*?// END ' + name),
      () =>
        '// BEGIN ' +
        name +
        '\n/* eslint-disable no-unused-vars */\n' +
        text +
        '\n/* eslint-enable no-unused-vars */\n// END ' +
        name,
    )
  source = source.replace(
    /\/\/ BEGIN PHOTO PICKER[\s\S]*?\/\/ END PHOTO PICKER/,
    () =>
      '// BEGIN PHOTO PICKER\nconst PHOTO_PICKER_HTML = ' +
      JSON.stringify(read('photo-picker.html')) +
      '\n// END PHOTO PICKER',
  )
  source = source
    .replace("const BASE_URL = 'http://127.0.0.1:18080'", 'const BASE_URL = settings.baseUrl')
    .replace(
      "const API_TOKEN = 'PASTE_GATEWAY_API_TOKEN_HERE'",
      'const API_TOKEN = settings.apiToken',
    )
  return 'function chatgpt_' + operation + '(draft, settings) {\n' + source + '\n}'
}

