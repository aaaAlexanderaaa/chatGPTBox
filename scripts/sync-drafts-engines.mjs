import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import prettier from 'prettier'

const directory = fileURLToPath(new URL('../docs/drafts/', import.meta.url))
const source = fs.readFileSync(path.join(directory, 'engine-actions.shared.txt'), 'utf8')
const actions = [
  ['list', 'Gemini List Conversations', '53C1CC08-081F-4A71-9C52-CF20966F31B1', 'list'],
  ['get', 'Gemini Get', 'C35EE2DF-69D1-440D-B2C4-0B361B59E680', 'download'],
  ['send', 'Gemini Send', 'B98B3854-467B-41B2-A8EB-AC400E8F568E', 'send'],
  ['older', 'Gemini Load Older Turns', '689EF2C7-1672-4619-B9B0-17C643FD09CE', 'history'],
]
for (const [action, name, uuid, icon] of actions) {
  const script = prettier.format(
    `/* global HTTP, app, draft */\n// Generated by scripts/sync-drafts-engines.mjs. Edit engine-actions.shared.txt.\nconst ACTION = '${action}'\nconst BASE_URL = 'http://127.0.0.1:18080'\nconst API_TOKEN = 'PASTE_GATEWAY_API_TOKEN_HERE'\nconst HISTORY_PAGE_SIZE = 20\n${source}`,
    {
      ...(await prettier.resolveConfig(path.join(directory, 'gemini-' + action + '.js'))),
      parser: 'babel',
    },
  )
  fs.writeFileSync(path.join(directory, 'gemini-' + action + '.js'), script)
  const stepId = uuid.slice(0, -1) + (uuid.endsWith('E') ? 'F' : 'E')
  fs.writeFileSync(
    path.join(directory, 'chatgptbox-gemini-' + action + '.draftsAction'),
    JSON.stringify(
      {
        uuid,
        name: 'ChatGPTBox ' + name,
        steps: [
          {
            uuid: stepId,
            type: 'script',
            platforms: 3,
            isEnabled: true,
            data: { script, allowAsync: 'false' },
          },
        ],
        shouldConfirm: false,
        disposition: 0,
        groupDisposition: 0,
        logLevel: 1,
        notificationType: 1,
        tintColor: 'green',
        keyUseIcon: true,
        icon,
        visibility: 480,
        assignTags: [],
      },
      null,
      2,
    ) + '\n',
  )
}
